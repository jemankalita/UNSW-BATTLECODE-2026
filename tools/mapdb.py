"""Bake the ranked maps into leviathan/mapdb.hpp.

    python tools/mapdb.py maps/default_small.map maps/queen_of_spades.map ...

The ladder plays a fixed pool of maps, and `GET /api/v1/maps` serves their
text. A dragon that knows the map it is on knows every kelp edge, where every
portal leads, and how often each tile spawns a pearl (the min/max gap that the
game itself never reveals). The bot still checks what it sees against the
baked map and drops it at the first disagreement.
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "leviathan" / "mapdb.hpp"

# Map files name the mirror axis: "y" mirrors across a vertical line, so x
# flips (Devil, Schooltime). logic.hpp: SYM_FLIP_X 0, SYM_FLIP_Y 1, SYM_ROTATE 2.
SYMMETRY = {"y": 0, "x": 1, "xy": 2}


def parse(path: pathlib.Path) -> dict:
    width = height = 0
    name = path.stem
    symmetry = -1
    tiles: dict[tuple[int, int], tuple[int, int]] = {}
    edges: dict[int, tuple[int, int]] = {}
    for line in path.read_text().splitlines():
        parts = line.split()
        if not parts:
            continue
        if parts[0] == "MAP":
            width, height = int(parts[1]), int(parts[2])
        elif parts[0] == "MAP_NAME":
            name = " ".join(parts[1:])
        elif parts[0] == "SYMMETRY":
            symmetry = SYMMETRY.get(parts[1], -1)
        elif parts[0] == "TILE":
            tiles[(int(parts[1]), int(parts[2]))] = (int(parts[3]), int(parts[4]))
        elif parts[0] == "EDGE":
            edges[int(parts[1])] = (int(parts[2]), int(parts[3]))
    if not width or not height:
        raise ValueError(f"{path}: no MAP line")
    return {"name": name, "w": width, "h": height, "sym": symmetry, "tiles": tiles, "edges": edges}


def encode(m: dict) -> tuple[str, str]:
    w, h = m["w"], m["h"]
    gaps: list[tuple[int, int]] = []
    tile_chars = []
    for y in range(h):
        for x in range(w):
            gap = m["tiles"].get((x, y), (0, 0))
            if gap not in gaps:
                gaps.append(gap)
            tile_chars.append(chr(ord("a") + gaps.index(gap)))
    if len(gaps) > 26:
        raise ValueError(f"{m['name']}: too many distinct pearl gaps")
    count = (2 * h + 1) * (w + 1)
    edge_chars = []
    pairs: dict[int, list[int]] = {}
    for index in range(count):
        kind, portal = m["edges"].get(index, (0, -1))
        edge_chars.append("#" if kind == 1 else "P" if kind == 2 else ".")
        if kind == 2:
            pairs.setdefault(portal, []).append(index)
    portals = []
    for pid, ends in sorted(pairs.items()):
        if len(ends) != 2:
            raise ValueError(f"{m['name']}: portal {pid} has {len(ends)} ends")
        portals += ends
    ident = "".join(c if c.isalnum() else "_" for c in m["name"].lower())
    lines = [f"static Gap const {ident}_gaps[] = {{{', '.join(f'{{{a}, {b}}}' for a, b in gaps)}}};"]
    lines.append(f"static int const {ident}_portals[] = {{{', '.join(map(str, portals)) or '-1'}}};")
    lines.append(f"static char const {ident}_tiles[] =")
    tiles = "".join(tile_chars)
    lines += [f'    "{tiles[i:i + w]}"' for i in range(0, len(tiles), w)]
    lines[-1] += ";"
    lines.append(f"static char const {ident}_edges[] =")
    edges = "".join(edge_chars)
    lines += [f'    "{edges[i:i + w + 1]}"' for i in range(0, len(edges), w + 1)]
    lines[-1] += ";"
    entry = (f'    {{"{m["name"]}", {w}, {h}, {m["sym"]}, {ident}_gaps, {len(gaps)}, {ident}_tiles, '
             f'{ident}_edges, {ident}_portals, {len(portals) // 2}}},')
    return "\n".join(lines), entry


def main() -> int:
    paths = [pathlib.Path(p) for p in sys.argv[1:]]
    if not paths:
        print(__doc__)
        return 1
    bodies, entries = [], []
    for path in paths:
        body, entry = encode(parse(path))
        bodies.append(body)
        entries.append(entry)
    OUT.write_text(
        "#pragma once\n\n"
        "// Generated by tools/mapdb.py from the ranked map pool. Do not edit.\n"
        "// Tiles: one letter per tile, row by row, indexing the gap table.\n"
        "// Edges: the map file's edge rows ('.' open, '#' kelp, 'P' portal);\n"
        "// portals: pairs of edge indices that lead into each other.\n"
        "namespace mapdb {\n\n"
        "struct Gap {\n    int lo;\n    int hi;\n};\n\n"
        "struct Known {\n    char const* name;\n    int width;\n    int height;\n    int symmetry;\n"
        "    Gap const* gaps;\n    int gap_count;\n    char const* tiles;\n    char const* edges;\n"
        "    int const* portals;\n    int portal_count;\n};\n\n"
        + "\n\n".join(bodies)
        + "\n\nstatic Known const MAPS[] = {\n" + "\n".join(entries) + "\n};\n\n"
        "static constexpr int MAP_COUNT = static_cast<int>(sizeof(MAPS) / sizeof(MAPS[0]));\n\n"
        "}  // namespace mapdb\n",
        newline="\n",
    )
    print(f"wrote {OUT} with {len(paths)} maps")
    return 0


if __name__ == "__main__":
    sys.exit(main())
